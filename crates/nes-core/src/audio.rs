//! Band-limited resampling of the APU's CPU-rate output.
//!
//! The APU's mixer runs at the CPU's clock — about 1.79 MHz — and the host
//! wants 44.1 or 48 kHz of it. Taking one reading per output sample (a
//! sample-and-hold) leaves every alias the mixer's square waves produce folded
//! into the audible band; this resampler instead treats each change in the
//! mixer's level as a step and convolves it with a band-limited impulse
//! response, which is the shape blargg's `blip_buf` has and the one Mesen's NES
//! sound mixer runs (`NesSoundMixer` feeds two `blip_t` buffers).
//!
//! The structure is blip's: a step at a fractional output position adds the
//! impulse response — sampled at 32 phases, linearly interpolated between them,
//! eight taps either side — starting at that position; the output is then the
//! running sum of those contributions (an integrator), each sample leaked
//! through a one-pole high-pass so the output stays AC coupled, as the
//! console's is.

/// Steps the impulse response is sampled at between one output sample and the
/// next. Blip's `phase_bits`.
const PHASES: usize = 32;
/// Output samples either side of the step that each phase's response spans.
const HALF_WIDTH: usize = 8;
/// Taps in one phase's response.
const TAPS: usize = HALF_WIDTH * 2;

/// What the high-pass keeps of the previous output sample. Blip's
/// `bass_shift = 9` over a 15-bit delta: `1 - 2^-9`.
const HIGH_PASS_LEAK: f64 = 1.0 - 1.0 / 512.0;

/// Slots in the impulse ring: a step's whole response, plus room for the
/// sample the clock is standing in and the one it is about to start.
const RING: usize = TAPS + 4;

