/// Resamples a stream of level changes from the APU's clock to the host's
/// sample rate.
///
/// The caller reports the level it now has; a change from the last one is a
/// step. [`BandLimiter::advance`] moves the input clock on, and
/// [`BandLimiter::read`] hands over the output samples that have been filled.
///
/// One input clock is worth about a fortieth of an output sample, so a step
/// reaches at most a sample or two past the one the clock is standing in:
/// a ring this size always has room for its whole response.
#[derive(Clone, Debug)]
pub struct BandLimiter {
    /// Output samples one input clock is worth.
    samples_per_clock: f64,
    /// How far into the current output sample the input clock sits.
    fraction: f64,
    /// How much of every not-yet-read sample's response has arrived.
    impulses: [f64; RING],
    /// The ring slot the next sample to read takes its impulse from.
    head: usize,
    /// Samples whose time has passed and can be read.
    ready: usize,
    /// The running sum of the impulses, high-passed sample by sample.
    integrator: f64,
}

impl BandLimiter {
    /// A resampler from `clock_rate` input clocks per second to `sample_rate`
    /// output samples per second.
    pub fn new(clock_rate: f64, sample_rate: f64) -> Self {
        Self {
            samples_per_clock: sample_rate / clock_rate,
            fraction: 0.0,
            impulses: [0.0; RING],
            head: 0,
            ready: 0,
            integrator: 0.0,
        }
    }

    /// Change the rates, keeping whatever is already in flight.
    ///
    /// A host that switches its device rate gets the rest of the buffer
    /// resampled at the new one, as Mesen's `UpdateRates` does.
    pub fn set_rates(&mut self, clock_rate: f64, sample_rate: f64) {
        self.samples_per_clock = sample_rate / clock_rate;
    }

    /// Report the level the mixer has now, adding a step if it changed.
    ///
    /// Blip's `AddDelta`: `last` is the caller's record of the level it
    /// reported before, so a mixer that is holding still costs nothing.
    pub fn set_level(&mut self, level: f64, last: &mut f64) {
        let delta = level - *last;
        if delta != 0.0 {
            self.add_delta(delta);
            *last = level;
        }
    }

    /// Add a step of `delta` at the position the input clock has reached.
    fn add_delta(&mut self, delta: f64) {
        let scaled = self.fraction * PHASES as f64;
        let phase = (scaled as usize).min(PHASES - 1);
        let between = scaled - phase as f64;

        // The step belongs to the sample the clock is standing in, which is
        // `ready` samples past the one `head` points at.
        let current = &KERNEL[phase];
        let next = &KERNEL[phase + 1];
        for tap in 0..TAPS {
            let interpolated = f64::from(current[tap])
                + (f64::from(next[tap]) - f64::from(current[tap])) * between;
            let slot = (self.head + self.ready + tap) % RING;
            self.impulses[slot] += interpolated * delta;
        }
    }

    /// One input clock: the output samples whose time has passed become
    /// readable.
    pub fn advance(&mut self) {
        self.fraction += self.samples_per_clock;
        while self.fraction >= 1.0 {
            self.fraction -= 1.0;
            self.ready += 1;
        }
    }

    /// Number of output samples waiting to be read.
    pub fn ready(&self) -> usize {
        self.ready
    }

    /// Take the next output sample, or `None` when none is ready.
    ///
    /// This is blip's `blip_read_samples`: the sample is the integrator, then
    /// the impulse waiting at that position joins it and its slot is freed for
    /// the ring to use again, and the high-pass leaks a 512th of the sample
    /// back out so the output stays AC coupled.
    pub fn read(&mut self) -> Option<f32> {
        if self.ready == 0 {
            return None;
        }
        let sample = self.integrator;
        self.integrator += self.impulses[self.head];
        self.integrator *= HIGH_PASS_LEAK;
        self.impulses[self.head] = 0.0;
        self.head = (self.head + 1) % RING;
        self.ready -= 1;
        Some(sample as f32)
    }
}

impl crate::state::StateField for BandLimiter {
    fn write(&self, w: &mut crate::state::StateWriter) {
        self.samples_per_clock.write(w);
        self.fraction.write(w);
        self.impulses.write(w);
        self.head.write(w);
        self.ready.write(w);
        self.integrator.write(w);
    }

    fn read(&mut self, r: &mut crate::state::StateReader<'_>) {
        self.samples_per_clock.read(r);
        self.fraction.read(r);
        self.impulses.read(r);
        self.head.read(r);
        self.ready.read(r);
        self.integrator.read(r);
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    /// The clock the APU's mixer runs at, and a typical device rate.
    const CLOCK: f64 = 1_789_773.0;
    const RATE: f64 = 48_000.0;

    /// Feed `seconds` worth of clocks of a level, collecting what comes out.
    fn run(limiter: &mut BandLimiter, level: impl Fn(f64) -> f32, seconds: f64) -> Vec<f32> {
        let mut last = 0.0f64;
        let mut out = Vec::new();
        let cycles = (CLOCK * seconds) as usize;
        for cycle in 0..cycles {
            limiter.set_level(f64::from(level(cycle as f64 / CLOCK)), &mut last);
            limiter.advance();
            while let Some(sample) = limiter.read() {
                out.push(sample);
            }
        }
        out
    }

    /// A step comes out at its own level: every phase's response sums to one,
    /// so the contributions that build the step add up to exactly the step.
    /// (The high-pass then leaks it away over about ten milliseconds, which the
    /// next test measures.)
    #[test]
    fn test_a_step_reaches_its_own_level() {
        let mut limiter = BandLimiter::new(CLOCK, RATE);
        let out = run(&mut limiter, |_| 0.5, 0.01);

        assert!(out.len() > 400, "the resampler produced samples");
        let peak = out[..20].iter().fold(0.0f32, |peak, s| peak.max(s.abs()));
        assert!(
            (peak - 0.5).abs() < 0.03,
            "a step to 0.5 comes out at 0.5, got {peak}"
        );
    }

    /// The output is AC coupled, as the console's is: blip's high-pass leaks a
    /// 512th of every sample, so a DC level decays away instead of sitting in
    /// the output forever.
    #[test]
    fn test_a_steady_level_decays_away() {
        let mut limiter = BandLimiter::new(CLOCK, RATE);
        let out = run(&mut limiter, |_| 0.5, 1.0);

        let early = out[1000].abs();
        let late = out[out.len() - 1].abs();
        assert!(late < early, "the level decays: {early} → {late}");
        assert!(late < 0.05, "and it is gone after a second, {late}");
    }

    /// A tone well inside the band keeps its amplitude.
    #[test]
    fn test_an_in_band_tone_keeps_its_amplitude() {
        let tone = 1_000.0;
        let mut limiter = BandLimiter::new(CLOCK, RATE);
        let out = run(
            &mut limiter,
            |seconds| (2.0 * std::f64::consts::PI * tone * seconds).sin() as f32,
            0.1,
        );

        let peak = out[out.len() / 2..]
            .iter()
            .fold(0.0f32, |m, s| m.max(s.abs()));
        assert!(
            (peak - 1.0).abs() < 0.05,
            "a 1 kHz tone keeps its amplitude, got {peak}"
        );
    }

    /// What the band limit is for: a tone above the output's Nyquist is not
    /// allowed to fold back into the audible band. At 30 kHz the fold lands at
    /// 18 kHz; sampling and holding puts it there at full strength, while the
    /// band-limited resampler leaves it tens of dB down.
    #[test]
    fn test_an_out_of_band_tone_folds_at_tens_of_db_down() {
        let tone = 30_000.0;
        let wave = |seconds: f64| (2.0 * std::f64::consts::PI * tone * seconds).sin() as f32;
        let samples = RATE as usize / 10;

        let mut limiter = BandLimiter::new(CLOCK, RATE);
        let filtered = run(&mut limiter, wave, 0.1);

        // The same input read once per output sample and held.
        let step = 1.0 / RATE;
        let held: Vec<f32> = (0..samples)
            .map(|index| wave(index as f64 * step))
            .collect();

        // How much of the 18 kHz alias is in each.
        let fold = |samples: &[f32]| {
            let tail = &samples[samples.len() / 2..];
            let mut sine = 0.0f64;
            let mut cosine = 0.0f64;
            for (index, sample) in tail.iter().enumerate() {
                let angle = 2.0 * std::f64::consts::PI * 18_000.0 * index as f64 / RATE;
                sine += *sample as f64 * angle.sin();
                cosine += *sample as f64 * angle.cos();
            }
            (sine * sine + cosine * cosine).sqrt() / tail.len() as f64
        };

        let band_limited = fold(&filtered);
        let sample_and_hold = fold(&held);
        assert!(
            sample_and_hold > 0.3,
            "the aliased 18 kHz tone is loud without the filter, got {sample_and_hold}"
        );
        assert!(
            band_limited * 10.0 < sample_and_hold,
            "the band-limited resampler keeps it 20 dB down: {band_limited} against {sample_and_hold}"
        );
    }
}
